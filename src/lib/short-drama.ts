/**
 * 微短剧特征判定：
 * 命中标题短剧关键字、套路命名或微短剧集数特征，用于严格从常规电影、电视剧、动漫、综艺中剔除
 */
export function isShortDramaTitle(title: string): boolean {
  if (!title) return false;
  const t = title.trim();
  // 1. 显式短剧标识
  if (/短剧|微剧|微短剧|爽文|竖屏剧/i.test(t)) return true;
  // 2. 典型微短剧核心题材与命名套路（战神/龙王/修罗/神医/天师/赘婿等）
  if (/(战神|龙王|修罗|修仙|神医|至尊|天师|阎王|龙皇|天君|龙婿|弃少|狂婿)(归来|下山|出狱|殿|令|霸婿|觉醒|无双|入赘)/.test(t)) return true;
  // 3. 典型总裁/甜宠/虐恋微短剧套路（闪婚/替嫁/真假千金/带球跑/隐婚等）
  if (/(闪婚|替嫁|真假|豪门|带球跑|隐婚|退婚|虐恋|独宠|霸道|千金|少夫人|夜少|顾少|傅少|陆少|墨少|沈少|霍少|厉少|顾总|傅总|陆总|墨总|沈总|霍总|厉总|薄总|封总|司总)(的|之|总裁|首富|大叔|娇妻|归来|继承人|马甲|心尖宠|掌心宝|甜妻)?/.test(t)) return true;
  // 4. 重生/穿越套路短剧
  if (/(重生|穿越|反穿|开局|逆袭|觉醒)之/.test(t)) return true;
  // 5. 短剧常见分集标注（如 第01-80集、全80集、全100集 等）
  if (/(第\d{2,3}-\d{2,3}集|全[5-9]\d集|全[1-9]\d{2,}集)/.test(t)) return true;
  return false;
}
